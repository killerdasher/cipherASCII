const FALLBACKS: ReadonlyMap<string, string> = new Map(FALLBACK_ENTRIES);

const BRAILLE_BASE = 0x2800;
const BRAILLE_END = 0x28ff;
const DOT_RAMP = ' .:-=+*#@';
const QUESTION = '?';

function isPrintableAscii(code: number): boolean {
  return code >= 0x20 && code <= 0x7e;
}

function countRaisedDots(code: number): number {
  let bits = code - BRAILLE_BASE;
  let count = 0;
  while (bits > 0) {
    count += bits & 1;
    bits >>>= 1;
  }
  return count;
}

/**
 * Returns a predictable ASCII replacement for a common Unicode art character
 * (block elements, box drawing, geometric shapes, arrows, quotes, ellipsis).
 *
 * @param ch - The character to translate.
 * @returns Its ASCII stand-in, or `null` when the character is unmapped.
 */
export function asciiFallback(ch: string): string | null {
  const mapped = FALLBACKS.get(ch);
  return mapped !== undefined ? mapped : null;
}

/**
 * Rewrites text as printable ASCII: ASCII characters are kept, characters in
 * the {@link asciiFallback} table collapse to their (possibly multi-character)
 * stand-in reduced to a single cell so grid width never changes, braille
 * characters (U+2800..U+28FF) map their raised-dot count onto the ramp
 * ` .:-=+*#@` (0 dots yields a space, 8 dots `@`), and every other character
 * becomes `?`.
 *
 * @param text - Text that may contain Unicode art characters.
 * @returns An ASCII-only string of identical cell count.
 */
export function toAsciiOnly(text: string): string {
  if (text.length === 0) {
    return '';
  }
  let out = '';
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (code !== undefined && isPrintableAscii(code)) {
      out += ch;
      continue;
    }
    if (code !== undefined && code >= BRAILLE_BASE && code <= BRAILLE_END) {
      out += DOT_RAMP.charAt(countRaisedDots(code));
      continue;
    }
    const mapped = asciiFallback(ch);
    if (mapped !== null) {
      out += mapped[0] ?? QUESTION;
      continue;
    }
    out += QUESTION;
  }
  return out;
}
